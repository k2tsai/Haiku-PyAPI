#!/usr/bin/env python3
# gen_test_constants.py — HOST-side: turn the gen_constants.py table +
# manual triage overrides into the guest test file test_constants.py.
#
#   python3 gen_test_constants.py /tmp/constants_table.py
#
import re
import sys

# (module, name) -> (expected_value, note). Overrides the table verdict where
# the resolver collided or the row needs human triage (2026-10-25).
OVERRIDES = {
    # global cursor ids (InterfaceDefs.h:74+); binding's 28/0x1c rows correct
    ("InterfaceDefs", "B_LEFT_ARROW"): 0x1c,
    ("InterfaceDefs", "B_RIGHT_ARROW"): 0x1d,
    ("InterfaceDefs", "B_UP_ARROW"): 0x1e,
    ("InterfaceDefs", "B_DOWN_ARROW"): 0x1f,
    # ControlLook m.attr lines shadow the global cursor ids with the NESTED
    # BControlLook values (0..3) — namespace defect; spec = the global id
    ("ControlLook", "B_LEFT_ARROW"): 0x1c,
    ("ControlLook", "B_RIGHT_ARROW"): 0x1d,
    ("ControlLook", "B_UP_ARROW"): 0x1e,
    ("ControlLook", "B_DOWN_ARROW"): 0x1f,
    ("Bitmap", "B_BITMAP_NO_SERVER_LINK"): 0x100,     # Bitmap.h:37
    # string-form defects: bound as Python str where C has an int
    ("Clipboard", "B_CLIPBOARD_CHANGED"): 0x434C4348,  # 'CLCH'
    ("Font", "B_NO_TRUNCATION"): 0xFFFFFFFF,            # '~0U'
    # legitimately string constants
    ("ParameterWeb", "B_GAIN"): "Gain",
    ("ParameterWeb", "B_EQUALIZATION"): "EQ",
    ("ParameterWeb", "B_MUTE"): "Mute",
    ("ParameterWeb", "B_WEB_ADC_CONVERTER"): "ADC",
    ("ParameterWeb", "B_WEB_DAC_CONVERTER"): "DAC",
    ("TimeZone", "kNameOfGmtZone"): "GMT",
    # C++ const values read from the headers
    ("MediaDefs", "B_MEDIA_MESSAGE_SIZE"): 16384,       # MediaDefs.h:777
    ("View", "B_FOLLOW_NONE"): 0,                       # View.h:109
    ("Archivable", "B_ASSUME_OWNERSHIP"): 0,             # Archivable.h:88
    ("Archivable", "B_DONT_ASSUME_OWNERSHIP"): 1,
    ("InterfaceDefs", "B_USE_DEFAULT_SPACING"): -1002,   # InterfaceDefs.h:260
    ("InterfaceDefs", "B_USE_ITEM_SPACING"): -1003,
    ("InterfaceDefs", "B_USE_ITEM_INSETS"): -1003,
    ("InterfaceDefs", "B_USE_HALF_ITEM_SPACING"): -1004,
    ("InterfaceDefs", "B_USE_HALF_ITEM_INSETS"): -1004,
    ("InterfaceDefs", "B_USE_WINDOW_SPACING"): -1005,
    ("InterfaceDefs", "B_USE_WINDOW_INSETS"): -1005,
    ("InterfaceDefs", "B_USE_SMALL_SPACING"): -1006,
    ("InterfaceDefs", "B_USE_SMALL_INSETS"): -1006,
    ("InterfaceDefs", "B_USE_CORNER_SPACING"): -1007,
    ("InterfaceDefs", "B_USE_CORNER_INSETS"): -1007,
    ("InterfaceDefs", "B_USE_BIG_SPACING"): -1008,
    ("InterfaceDefs", "B_USE_BIG_INSETS"): -1008,
    ("InterfaceDefs", "B_USE_BORDER_SPACING"): -1009,
    ("InterfaceDefs", "B_USE_BORDER_INSETS"): -1009,
}

# modules not in the Jamfile build (commented out / orphan sources)
NOT_BUILT = {"OptionControl", "BlockCache", "ScreenSaver", "MimeSnifferAddon",
             "GraphicsCard", "InputServerDevice", "InputServerFilter",
             "InputServerMethod", "MailProtocol", "MailFilter", "NetworkProfile",
             "NetworkSettingsAddOn", "module", "bus_manager", "ACPI",
             "cpufreq", "cpuidle", "Joystick", "USBKit", "A2D", "D2A",
             "DigitalPort", "bios", "GroupView", "Shelf", "SplitView",
             "SpaceLayoutItem", "LayoutBuilder", "OptionPopUp"}

SKIP = {
    ("Size", "B_SIZE_UNSET"),                      # BSize object
    ("MediaDefs", "B_CODEC_TYPE_INFO"),            # extern const variable
    ("StorageDefs", "B_CLONE_KIND"),               # removed from beta6
    ("InterfaceDefs", "B_HANGUL"),                 # removed from beta6
    ("InterfaceDefs", "B_HANGUL_HANJA"),           # removed from beta6
    ("CatalogData", "gCatalogAddOnPriority"),      # not resolvable
}


def main():
    table_src = open(sys.argv[1]).read()
    rows = re.findall(
        r"\('(\w+)', '(\w+)', '([^']*)', (.*?), '(?:DRIFT|STR-FORM|UNRESOLVED|ok)', '\w+'\)",
        table_src)
    seen = {}
    for mod, name, lit, real in rows:
        if mod in NOT_BUILT or (mod, name) in SKIP:
            continue
        if (mod, name) in OVERRIDES:
            expected = OVERRIDES[(mod, name)]
        elif real.strip() == "None":
            try:
                expected = int(lit, 0)
            except ValueError:
                continue
        else:
            expected = eval(real.strip(), {"__builtins__": {}}, {})
        seen.setdefault((mod, name), (mod, name, expected))

    data = sorted(seen.values(), key=lambda t: (t[0], t[1]))
    out = ["#!/usr/bin/env python3",
           "# test_constants.py — GENERATED by gen_test_constants.py.",
           "# Spec = the beta6 C headers: every m.attr constant the bindings",
           "# expose must equal the header value, and be an int where C has an",
           "# int (string-form 4ccs are defects). One subprocess per module",
           "# (the TSS-key wall forbids ~100 module imports in one process).",
           "import json, os, subprocess, sys",
           "import common",
           "",
           "CHILD = os.path.join(os.path.dirname(os.path.abspath(__file__)),",
           "                     \"child_constants.py\")",
           "ROWS = ["]
    for mod, name, expected in data:
        out.append("    (%r, %r, %r)," % (mod, name, expected))
    out += ["]",
            "",
            "BY_MODULE = {}",
            "for mod, name, expected in ROWS:",
            "    BY_MODULE.setdefault(mod, []).append((name, expected))",
            "",
            "def per_module(mod):",
            "    # solo first; a FAILED solo leaves partial C++ registrations,",
            "    # so the closure retry runs in a FRESH subprocess",
            "    rows_j = json.dumps(BY_MODULE[mod])",
            "    p = subprocess.run([sys.executable, CHILD, mod, rows_j, \"solo\"],",
            "                       cwd=\"/\", capture_output=True, text=True,",
            "                       timeout=120)",
            "    line = [l for l in p.stdout.splitlines() if l.startswith(\"JSON \")]",
            "    if not line:",
            "        p = subprocess.run([sys.executable, CHILD, mod, rows_j,",
            "                            \"closure\"],",
            "                           cwd=\"/\", capture_output=True, text=True,",
            "                           timeout=120)",
            "        line = [l for l in p.stdout.splitlines() if l.startswith(\"JSON \")]",
            "    if not line:",
            "        common.check(\"constants:%s\" % mod, lambda: (_ for _ in ()).throw(",
            "            AssertionError(\"import failed (solo+closure): \" + (p.stderr.strip().splitlines() or [\"?\"])[-1][:160])))",
            "        return",
            "    res = json.loads(line[0][5:])",
            "    bad = [r for r in res if r[1] != \"OK\"]",
            "    if bad:",
            "        detail = \"; \".join(\"%s: got %s (want %s)\" %",
            "                           (r[0], r[2], dict(BY_MODULE[mod]).get(r[0]))",
            "                           for r in bad[:5])",
            "        common.check(\"constants:%s\" % mod,",
            "                     lambda d=detail: (_ for _ in ()).throw(AssertionError(d)))",
            "    else:",
            "        common.check(\"constants:%s\" % mod, lambda n=len(res): \"%d ok\" % n)",
            "",
            "# Runtime-aware strategy (common.import_strategy measures the TSS",
            "# pool): if the WHOLE union closure fits one process, one child",
            "# imports everything (fast); else one fault-isolated child per",
            "# module (Haiku's ~507-key wall). A chunk failure at module X",
            "# poisons that child -> per-module fallback for X and the rest.",
            "union = common.closure(*BY_MODULE.keys())",
            "strat = common.import_strategy(union)",
            "print(\"strategy: %s (union=%d modules)\" % (strat, len(union)))",
            "if strat == \"single\":",
            "    p = subprocess.run([sys.executable, CHILD, \"chunk\",",
            "                         json.dumps(union), json.dumps(BY_MODULE)],",
            "                        cwd=\"/\", capture_output=True, text=True,",
            "                        timeout=900)",
            "    line = [l for l in p.stdout.splitlines() if l.startswith(\"JSON \")]",
            "    done = set()",
            "    if line:",
            "        payload = json.loads(line[0][5:])",
            "        for m, res in payload[\"results\"].items():",
            "            done.add(m)",
            "            bad = [r for r in res if r[1] != \"OK\"]",
            "            if bad:",
            "                detail = \"; \".join(\"%s: got %s (want %s)\" %",
            "                                   (r[0], r[2],",
            "                                    dict(BY_MODULE[m]).get(r[0]))",
            "                                   for r in bad[:5])",
            "                common.check(\"constants:%s\" % m,",
            "                             lambda d=detail, m=m: (_ for _ in ()).throw(AssertionError(d)))",
            "            else:",
            "                common.check(\"constants:%s\" % m, lambda n=len(res), m=m: \"%d ok\" % n)",
            "        rest = [m for m in BY_MODULE if m not in done]",
            "        if rest:",
            "            print(\"chunk stopped at %s -> per-module fallback for %d\" %",
            "                  (payload[\"failed_at\"], len(rest)))",
            "    else:",
            "        rest = list(BY_MODULE)",
            "    for mod in rest:",
            "        per_module(mod)",
            "else:",
            "    for mod in sorted(BY_MODULE):",
            "        per_module(mod)",
            "",
            "sys.exit(common.report(\"test_constants\"))",
            ""]
    print("\n".join(out))


if __name__ == "__main__":
    main()
